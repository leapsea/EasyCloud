package main

import (
	"fmt"
	"hash/crc32"
	"sort"
	"strings"

	"github.com/easycloud/easycloud/pkg/pluginsdk"
)

type config struct {
	OutputDir       string `json:"outputDir"`     // where smb.conf etc. are written (plugin-relative or absolute)
	ContainerData   string `json:"containerData"` // data root path inside the Samba container
	ForceUID        int    `json:"forceUid"`      // files written over SMB are owned by this uid/gid
	ForceGID        int    `json:"forceGid"`
	Workgroup       string `json:"workgroup"`
	ManageContainer bool   `json:"manageContainer"`
	DockerSocket    string `json:"dockerSocket"`
	Image           string `json:"image"`
	ContainerName   string `json:"containerName"`
	HostDataRoot    string `json:"hostDataRoot"`  // data root as seen by the Docker host
	HostConfigDir   string `json:"hostConfigDir"` // OutputDir as seen by the Docker host
	SMBPort         int    `json:"smbPort"`
}

func (c *config) defaults() {
	if c.OutputDir == "" {
		c.OutputDir = "samba"
	}
	if c.ContainerData == "" {
		c.ContainerData = "/data"
	}
	if c.ForceUID == 0 {
		c.ForceUID = 1000
	}
	if c.ForceGID == 0 {
		c.ForceGID = c.ForceUID
	}
	if c.Workgroup == "" {
		c.Workgroup = "WORKGROUP"
	}
	if c.DockerSocket == "" {
		c.DockerSocket = "/var/run/docker.sock"
	}
	if c.Image == "" {
		c.Image = "ghcr.io/crazy-max/samba:latest"
	}
	if c.ContainerName == "" {
		c.ContainerName = "easycloud-samba"
	}
	if c.SMBPort == 0 {
		c.SMBPort = 445
	}
}

// uidFor gives every account a stable unix uid inside the container.
func uidFor(name string) int { return 20000 + int(crc32.ChecksumIEEE([]byte(name))%40000) }

func quoteList(us []string) string {
	q := make([]string, len(us))
	for i, u := range us {
		q[i] = `"` + u + `"`
	}
	return strings.Join(q, " ")
}

// smbConf renders the Samba configuration for the snapshot.
func smbConf(c config, req *pluginsdk.SyncRequest) string {
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by EasyCloud samba-gateway. Do not edit: changes are overwritten.
[global]
   workgroup = %s
   server string = EasyCloud
   server role = standalone server
   security = user
   passdb backend = smbpasswd:/config/smbpasswd
   map to guest = never
   restrict anonymous = 2
   server min protocol = SMB2_10
   smb encrypt = desired
   load printers = no
   printing = bsd
   printcap name = /dev/null
   disable spoolss = yes
   unix extensions = no
   follow symlinks = no
   wide links = no
   veto files = /.easycloud/
   delete veto files = no
   vfs objects = catia fruit streams_xattr
   fruit:metadata = stream
   log level = 1
`, c.Workgroup)
	shares := append([]pluginsdk.ShareDef{}, req.Shares...)
	sort.Slice(shares, func(i, j int) bool { return shares[i].Name < shares[j].Name })
	for _, s := range shares {
		valid := append(append([]string{}, s.ReadUsers...), s.WriteUsers...)
		if len(valid) == 0 {
			continue
		}
		sort.Strings(valid)
		path := strings.TrimRight(c.ContainerData+"/"+strings.Trim(s.Path, "/"), "/")
		fmt.Fprintf(&b, `
[%s]
   path = %s
   browseable = yes
   valid users = %s
   read only = yes
`, s.Name, path, quoteList(valid))
		if len(s.WriteUsers) > 0 {
			fmt.Fprintf(&b, "   write list = %s\n", quoteList(s.WriteUsers))
		}
		fmt.Fprintf(&b, "   force user = easycloud\n   force group = easycloud\n   create mask = 0644\n   directory mask = 0755\n")
	}
	return b.String()
}

// smbpasswd renders the smbpasswd file (NT hashes only; no LM hashes).
func smbpasswd(req *pluginsdk.SyncRequest) string {
	var b strings.Builder
	accts := append([]pluginsdk.Account{}, req.Accounts...)
	sort.Slice(accts, func(i, j int) bool { return accts[i].Username < accts[j].Username })
	for _, a := range accts {
		fmt.Fprintf(&b, "%s:%d:XXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX:%s:[U          ]:LCT-00000000:\n", a.Username, uidFor(a.Username), a.NTHash)
	}
	return b.String()
}

// entrypoint creates matching unix users, then runs smbd in the foreground.
// reload.sh does the same for running containers.
func scripts(c config, req *pluginsdk.SyncRequest) (entry, reload string) {
	var users strings.Builder
	fmt.Fprintf(&users, "#!/bin/sh\nset -e\n")
	fmt.Fprintf(&users, "getent group easycloud >/dev/null || addgroup -g %d easycloud 2>/dev/null || groupadd -g %d easycloud\n", c.ForceGID, c.ForceGID)
	fmt.Fprintf(&users, "getent passwd easycloud >/dev/null || adduser -D -H -u %d -G easycloud easycloud 2>/dev/null || useradd -M -u %d -g easycloud easycloud\n", c.ForceUID, c.ForceUID)
	for _, a := range req.Accounts {
		fmt.Fprintf(&users, "getent passwd %[1]s >/dev/null || adduser -D -H -u %[2]d %[1]s 2>/dev/null || useradd -M -u %[2]d %[1]s\n", a.Username, uidFor(a.Username))
	}
	common := users.String()
	entry = common + "mkdir -p /var/lib/samba/private /run/samba\nexec smbd --foreground --no-process-group --debug-stdout --configfile=/config/smb.conf\n"
	reload = common + "smbcontrol --configfile=/config/smb.conf smbd reload-config\n"
	return entry, reload
}
